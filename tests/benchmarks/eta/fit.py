import sys
import json, re
import numpy as np
from pathlib import Path
from extract import passes
root = Path(next((a for a in sys.argv[1:] if not a.startswith('--')), 'build/eta-recordings')).resolve()

def fit(data):
    # Five numbers: two assembly kernels, two LU backends, one small overhead.
    rows=[p for d in data for p in d['passes']]
    assembly=[]; interface=[]
    for p in rows:
        c,n=p['c']/1000,p['n']/1000
        assembly.append(p['durations'][1]*p['threads'][0]/(c*c))
        if n>c:
            points=[]
            for e in p['lines']:
                m=re.match(r'MMTL_PROGRESS assembly (\d+) (\d+)',e['line'])
                if m and p['boundaries'][4]<=e['ms']<=p['boundaries'][5]:
                    points.append((int(m[1]),(e['ms']-p['boundaries'][4])/1000))
            if points:
                split=float(np.interp(p['c'],[x[0] for x in points],[x[1] for x in points]))
                interface.append(max(0,p['durations'][4]-split)*p['threads'][1]/((n-c)*n))
    conductor=float(np.median(assembly)); dielectric=float(np.median(interface))
    overhead=float(np.median([p['durations'][0] for p in rows]))
    result={'conductor':conductor,'dielectric':dielectric,'overhead':overhead,'lu':{}}
    for backend in ['serial','eigen']:
        pp=[p for p in rows if p['backend']==backend]
        if not pp:continue
        lu=float(np.median([p['durations'][stage]/(nodes/1000)**3 for p in pp for nodes,stage in [(2*p['c'],2),(p['nodes'],5)]]))
        result['lu'][backend]=lu
    return result
if __name__ == '__main__':
    data = [passes(json.loads(p.read_text(encoding='utf-8'))) for p in sorted(root.glob('0??.json'))]
    (root / 'extracted.json').write_text(json.dumps(data), encoding='utf-8')
    (root / 'cost-model.json').write_text(json.dumps(fit(data), indent=2), encoding='utf-8')
    models = {d['label']: fit([x for x in data if x['group'] != d['group']]) for d in data}
    (root / 'heldout-models.json').write_text(json.dumps(models), encoding='utf-8')
    print('Recorded cases:', len(data))
    print(json.dumps(fit(data), indent=2))

    if '--write-model' in sys.argv:
        target=Path('src/solver/measuredWorkCosts.mjs')
        target.write_text('// Generated by tests/benchmarks/eta/fit.py. Costs use matrix dimensions / 1000 and seconds.\nexport const measuredWorkCosts = '+json.dumps(fit(data),indent=2)+';\n',encoding='utf-8')
        print('Updated',target)
